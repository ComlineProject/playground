/// A tiny seeded PRNG (mulberry32). The fault rolls use it instead of
/// `Math.random()` so a stepped run with a fixed `Session.seed` produces the
/// same frame sequence every time — the basis for record & replay (2e).

export type Rng = () => number;

export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
